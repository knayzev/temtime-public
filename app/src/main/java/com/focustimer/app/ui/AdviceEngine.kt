package com.focustimer.app.ui

/**
 * Rule-based tips derived from body/age data. This isn't a literal per-value lookup table
 * (that would mean millions of rows for every age/height/weight combination) — instead it
 * covers the full supported range (age 10-95, height 110-220cm, weight 35-220kg) with fine
 * enough brackets per dimension (age, BMI, height, gender) that the combined output varies
 * meaningfully across users instead of collapsing into the same 3-4 generic messages.
 * Not medical advice — just sensible defaults to nudge the user toward a healthier routine.
 */
fun buildAdvice(weightKgText: String, heightCmText: String, ageText: String, gender: String): List<String> {
    val advice = mutableListOf<String>()
    val age = ageText.toIntOrNull()
    val weight = weightKgText.toDoubleOrNull()
    val heightCm = heightCmText.toDoubleOrNull()
    val heightM = heightCm?.div(100)
    val isFemale = gender == "Женский"
    val isMale = gender == "Мужской"

    advice += sleepAdviceFor(age)

    if (age != null && age < 18) {
        advice += childBmiAdvice(age, weight, heightM)
    } else if (weight != null && heightM != null && heightM > 0) {
        val bmi = weight / (heightM * heightM)
        advice += adultBmiAdvice(bmi, age, isFemale, isMale)
    } else {
        advice += "Заполните вес и рост выше, чтобы получить более точный совет по активности."
    }

    if (weight != null) {
        weightExtremeAdvice(weight, age)?.let { advice += it }
    }

    if (heightCm != null) {
        heightAdvice(heightCm)?.let { advice += it }
    }

    advice += genderAdvice(isFemale, isMale, age)
    advice += focusRoutineAdvice(age)

    return advice
}

private fun sleepAdviceFor(age: Int?): String = when {
    age == null -> "Взрослым обычно рекомендуют 7–9 часов сна."
    age < 13 -> "В возрасте 10–12 лет организму нужно 9–12 часов сна — старайтесь укладываться спать не позднее 21:30."
    age < 16 -> "Подросткам 13–15 лет рекомендуется 8–10 часов сна, особенно в учебные дни."
    age < 18 -> "В 16–17 лет всё ещё важно спать 8–10 часов — недосып в этом возрасте сильнее всего бьёт по концентрации."
    age < 26 -> "В 18–25 лет обычно достаточно 7–9 часов, но соблазн лечь позже велик — держите постоянный режим."
    age < 36 -> "В 26–35 лет рекомендуется 7–9 часов сна: это база для восстановления при высокой рабочей нагрузке."
    age < 46 -> "В 36–45 лет держите 7–8 часов сна и старайтесь не брать работу в постель — это заметно влияет на качество сна."
    age < 56 -> "В 46–55 лет рекомендуется 7–8 часов; в этом возрасте особенно важен стабильный ритм отхода ко сну."
    age < 66 -> "В 56–65 лет обычно достаточно 7–8 часов, но чувствительность к кофеину вечером возрастает — ограничьте его после обеда."
    age < 76 -> "В 66–75 лет рекомендуется 7–8 часов ночного сна; короткий дневной сон 20–30 минут — это нормально и полезно."
    else -> "В возрасте 76+ часто достаточно 7–8 часов с более гибким графиком; дневной отдых 20–30 минут помогает компенсировать более чуткий ночной сон."
}

private fun childBmiAdvice(age: Int, weight: Double?, heightM: Double?): String {
    val base = if (age < 13) {
        "Детям рекомендуется минимум 60 минут активной игры или спорта в день."
    } else {
        "Подросткам рекомендуется минимум 60 минут умеренной или высокой физической активности в день, включая силовые упражнения 2–3 раза в неделю."
    }
    if (weight == null || heightM == null || heightM <= 0) return base
    return "$base Индекс массы тела у детей и подростков оценивается по возрастным перцентилям, а не по взрослым нормам — если вес заметно выходит за пределы возрастной нормы, стоит обсудить это с педиатром."
}

private fun adultBmiAdvice(bmi: Double, age: Int?, isFemale: Boolean, isMale: Boolean): String {
    val seniorNote = if (age != null && age >= 65) " После 65 лет для суставов особенно хорошо подходят низкоударные нагрузки: плавание, скандинавская ходьба, велотренажёр." else ""
    return when {
        bmi < 16.0 ->
            "Индекс массы тела сильно ниже нормы (выраженный дефицит массы) — это повод обсудить питание и самочувствие с врачом; самостоятельно наращивать нагрузку в этом состоянии не стоит."
        bmi < 17.0 ->
            "Индекс массы тела заметно ниже нормы — сделайте акцент на регулярном полноценном питании и лёгких силовых упражнениях 2 раза в неделю, без интенсивного кардио."
        bmi < 18.5 ->
            "Индекс массы тела немного ниже нормы — добавьте силовые тренировки 2–3 раза в неделю и следите, чтобы питание покрывало расход энергии."
        bmi < 25.0 ->
            "Индекс массы тела в норме — поддерживайте активность: минимум 150 минут в неделю умеренной нагрузки, около 20–30 минут в день.$seniorNote"
        bmi < 30.0 ->
            "Индекс массы тела немного повышен — старайтесь проходить не менее 8000 шагов в день и добавьте 2 силовые тренировки в неделю.$seniorNote"
        bmi < 35.0 ->
            "Индекс массы тела повышен (ожирение I степени) — начните с лёгкой активности: ходьба 20–30 минут в день, постепенно увеличивая длительность и темп.$seniorNote"
        bmi < 40.0 ->
            "Индекс массы тела значительно повышен (ожирение II степени) — низкоударные нагрузки (плавание, велосипед, ходьба) безопаснее для суставов, чем бег; имеет смысл обсудить план с врачом.$seniorNote"
        else ->
            "Индекс массы тела существенно повышен (ожирение III степени) — прежде чем наращивать нагрузку, стоит проконсультироваться с врачом и подобрать безопасный для суставов формат активности.$seniorNote"
    } + if (isFemale && bmi < 18.5) " Женщинам с дефицитом массы особенно важно следить за железом и кальцием в рационе." else ""
}

private fun weightExtremeAdvice(weight: Double, age: Int?): String? = when {
    weight < 35.0 -> "Указанный вес очень низкий — рекомендуем обсудить питание и самочувствие с врачом."
    weight in 35.0..39.9 && (age == null || age >= 18) -> "Вес заметно ниже типичного для взрослого человека — стоит проверить, хватает ли калорий и белка в рационе."
    weight > 180.0 -> "При весе в этом диапазоне особенно полезны низкоударные тренировки (плавание, велосипед) — они снижают нагрузку на суставы и позвоночник."
    weight > 150.0 -> "Начинайте активность постепенно и отдавайте предпочтение низкоударным нагрузкам — так суставы адаптируются безопаснее."
    else -> null
}

private fun heightAdvice(heightCm: Double): String? = when {
    heightCm < 150.0 -> "При невысоком росте особенно важно настроить рабочее место: высота стула и монитора должны позволять держать спину прямо, а ноги — полностью стоять на полу или подставке."
    heightCm > 195.0 -> "При высоком росте проверьте рабочее место: слишком низкий стол или монитор заставляют сутулиться — поднимите монитор на уровень глаз и следите за пространством для ног."
    heightCm > 185.0 -> "При вашем росте обратите внимание на высоту стола и монитора, чтобы не сутулиться во время долгой работы."
    else -> null
}

private fun genderAdvice(isFemale: Boolean, isMale: Boolean, age: Int?): String = when {
    isFemale && age != null && age >= 45 ->
        "Женщинам после 45 особенно важны кальций, витамин D и силовые упражнения — они поддерживают плотность костей."
    isFemale ->
        "Женщинам, особенно при высокой физической нагрузке, стоит следить за железом в рационе."
    isMale && age != null && age >= 40 ->
        "Мужчинам после 40 рекомендуется регулярно проверять сердечно-сосудистую систему и не пренебрегать кардионагрузкой 2–3 раза в неделю."
    isMale ->
        "Мужчинам стоит сочетать силовые тренировки с кардионагрузкой — это лучше поддерживает сердце и сосуды в долгосрочной перспективе."
    else ->
        "Сочетайте силовые упражнения с кардионагрузкой — так поддерживаются и мышцы, и сердечно-сосудистая система."
}

private fun focusRoutineAdvice(age: Int?): String = when {
    age != null && age < 16 -> "Для учёбы подойдут блоки покороче — 20–30 минут работы, затем 5–10 минут перерыва."
    age != null && age < 18 -> "Попробуйте блоки по 30–40 минут с перерывами 10 минут — так легче удерживать концентрацию на учёбе."
    age != null && age >= 66 -> "Блоки по 30–40 минут с перерывом 10–15 минут обычно комфортнее для долгой концентрации, чем длинные подходы."
    else -> "Работайте блоками по 45–50 минут, затем делайте перерыв 10–15 минут. На перерыве лучше пройтись или почитать, а не листать телефон — так мозг действительно отдыхает."
}
